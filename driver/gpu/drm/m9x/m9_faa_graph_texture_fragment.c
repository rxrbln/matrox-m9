static u8 operand(u32 v, const struct variant *t)
{
	switch (v) {
	case RG:
		return t->rg;
	case BA:
		return t->ba;
	case XRG:
		return 0x80 | t->rg;
	case XBA:
		return 0x80 | t->ba;
	default:
		return v;
	}
}

static void emit(u8 *p, u32 *n, struct form f)
{
	m9_cmd_put(p + 8 * *n, ((u32)(f.a & 7) << 29) | ((u32)f.b << 22) |
		   ((u32)f.c << 15) | ((u32)f.dst << 8) | ((u32)f.cls << 5) |
		   f.op);
	m9_cmd_put(p + 8 * *n + 4, f.control | (f.a >> 3));
	++*n;
}

/* A float of an integer 0..255 (the D3D alpha reference). */
static u32 float_bits(u32 v)
{
	u32 e = 0;

	if (!v)
		return 0;
	while (!(v & 0x800000)) {
		v <<= 1;
		e++;
	}
	return ((150 - e) << 23) | (v & 0x7fffff);
}

int m9x_faa_texture_fragment_build(u32 kind, u32 word, u8 *program,
				   u32 program_capacity, u8 *constants,
				   u32 constant_capacity,
				   struct m9x_faa_texture_fragment_iface *iface)
{
	bool modulate = word & PARHELIA_M9_FAA_FRAGMENT_MODULATE;
	bool blend = word & PARHELIA_M9_FAA_FRAGMENT_BLEND;
	bool test = word & PARHELIA_M9_FAA_FRAGMENT_ALPHA_TEST;
	u32 src = (word >> 4) & 15, dst = (word >> 8) & 15;
	u32 func = (word >> 12) & 3, ref = (word >> 16) & 255;
	u32 utility[14], k = 0, i, n = 0, slots, pairs;
	const struct factor_tail *tail = NULL;
	const struct variant *t;
	u8 image[M9_FAA_TEXTURE_FRAGMENT_MAX_PROGRAM];

	if (!program || !constants || !iface || kind > 1 ||
	    (word & ~PARHELIA_M9_FAA_FRAGMENT_MASK) ||
	    (!blend && (src || dst)) ||
	    (!test && (func || ref)) ||
	    func > PARHELIA_M9_FAA_ALPHA_GREATER)
		return -EINVAL;
	if (blend) {
		for (i = 0; i < ARRAY_SIZE(factor_tail); i++)
			if (factor_tail[i].src == src &&
			    factor_tail[i].dst == dst)
				tail = &factor_tail[i];
		if (!tail)
			return -EINVAL;
	}
	t = &variants[(kind == M9_FAA_PROGRAM_DUAL) * 8 + modulate * 4 +
		      blend * 2 + test];
	/* C3: stage-1 select (0,1), blend (0,0), reference, conversion
	 * (0,255) and (2+e,1), then the combine's (0,1),(1,0.5).
	 */
	if (!kind && !modulate) {
		utility[k++] = 0;
		utility[k++] = 0x3f800000;
	}
	if (blend) {
		utility[k++] = 0;
		utility[k++] = 0;
	}
	if (test) {
		utility[k++] = float_bits(ref);
		utility[k++] = float_bits(ref);
		utility[k++] = 0;
		utility[k++] = 0x437f0000;
		utility[k++] = 0x40000001;
		utility[k++] = 0x3f800000;
	}
	utility[k++] = 0;
	utility[k++] = 0x3f800000;
	utility[k++] = 0x3f800000;
	utility[k++] = 0x3f000000;
	slots = t->count + (tail ? 2 : 0);
	pairs = k / 2;
	if (program_capacity < slots * 8 || constant_capacity < pairs * 8 ||
	    m9_cmd_overlap(program, slots * 8, constants, pairs * 8))
		return -EINVAL;
	for (i = 0; i < t->count; i++) {
		struct form f = t->forms[i];

		if (f.dst == 0x40)
			f.cls = func;
		emit(image, &n, f);
	}
	if (tail) {
		u32 control = tail->control |
			      (tail->k == K_LAST ? pairs - 1 : tail->k) << 14;
		struct form rgb = { 0x1d, 4, 0x2d, operand(tail->rgb[0], t),
				    operand(tail->rgb[1], t),
				    operand(tail->rgb[2], t), control };
		struct form ba = { 0x1e, 4, 0x2d, operand(tail->ba[0], t),
				   operand(tail->ba[1], t),
				   operand(tail->ba[2], t), control };
		bool rg_first = t->rg_first || tail->rg_first;

		emit(image, &n, rg_first ? rgb : ba);
		emit(image, &n, rg_first ? ba : rgb);
	}
	/* One finish mark four slots before the end. */
	m9_cmd_put(image + 8 * (n - 4) + 4,
		   m9_cmd_get(image + 8 * (n - 4) + 4) | 0x40000000);
	memcpy(program, image, slots * 8);
	for (i = 0; i < k; i++)
		m9_cmd_put(constants + 4 * i, utility[i]);
	iface->program_bytes = slots * 8;
	iface->constant_bytes = pairs * 8;
	iface->raster_f0 = blend ? 0xc5008200 : test ? 0xc4008200 : 0xc4008600;
	iface->usage = t->usage;
	return 0;
}

int m9x_faa_texture_fragment_check(u32 kind, u32 word, const u8 *program,
				   u32 program_bytes, const u8 *constants,
				   u32 constant_bytes,
				   struct m9x_faa_texture_fragment_iface *iface)
{
	u8 p[M9_FAA_TEXTURE_FRAGMENT_MAX_PROGRAM];
	u8 c[M9_FAA_TEXTURE_FRAGMENT_MAX_CONSTANTS];
	int ret;

	if (!program || !constants || !iface)
		return -EINVAL;
	ret = m9x_faa_texture_fragment_build(kind, word, p, sizeof(p), c,
					     sizeof(c), iface);
	if (ret)
		return ret;
	if (program_bytes != iface->program_bytes ||
	    constant_bytes != iface->constant_bytes ||
	    memcmp(program, p, program_bytes) ||
	    memcmp(constants, c, constant_bytes))
		return -EINVAL;
	return 0;
}
